const assert = require("assert")
const fs = require("fs")
const path = require("path")

const projectRoot = path.resolve(__dirname, "..", "..")
const backendRoot = path.join(projectRoot, "backend")
const dotenv = require(path.join(backendRoot, "node_modules", "dotenv"))
const { Client } = require(path.join(backendRoot, "node_modules", "pg"))

dotenv.config({ path: path.join(backendRoot, ".env"), quiet: true })

const schemaName = `atec_mpi_uat_${process.pid}`
if (!/^atec_mpi_uat_\d+$/.test(schemaName)) throw new Error("Unsafe MPI UAT schema name")

function connectionConfig(database) {
  return {
    host: process.env.DB_HOST || "127.0.0.1",
    port: Number(process.env.DB_PORT || 5432),
    database,
    user: process.env.DB_USER,
    password: process.env.DB_PASSWORD,
    application_name: "atec-mpi-database-uat"
  }
}

function migrationBody(contents) {
  return contents
    .replace(/^\s*BEGIN\s*;\s*/i, "")
    .replace(/\s*COMMIT\s*;\s*$/i, "")
}

async function bootstrap(client) {
  await client.query(`
    CREATE SCHEMA ${schemaName};

    CREATE TABLE atec.tblusers (
      userid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username text NOT NULL,
      fullname text,
      usersignature text,
      role text NOT NULL,
      is_active boolean NOT NULL DEFAULT true
    );

    CREATE TABLE atec.tblclients (
      clientid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      clientname text NOT NULL,
      archived boolean NOT NULL DEFAULT false
    );

    CREATE TABLE atec.tblsites (
      siteid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      clientid integer NOT NULL REFERENCES atec.tblclients(clientid),
      sitename text NOT NULL
    );

    CREATE TABLE atec.tblsection (
      sectionid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      clientid integer NOT NULL REFERENCES atec.tblclients(clientid),
      siteid integer REFERENCES atec.tblsites(siteid),
      sectionname text NOT NULL
    );

    CREATE TABLE atec.tblasset (
      assetid integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      clientid integer NOT NULL REFERENCES atec.tblclients(clientid),
      siteid integer REFERENCES atec.tblsites(siteid),
      sectionid integer REFERENCES atec.tblsection(sectionid),
      description text,
      serialno text,
      assettagno text,
      archived boolean NOT NULL DEFAULT false
    );
  `)

  const migration = fs.readFileSync(
    path.join(projectRoot, "database", "2026-07-29-magnetic-particle-inspection-module.sql"),
    "utf8"
  )
  await client.query(migrationBody(migration))
}

async function runAssertions(client) {
  const numbers = []
  for (let index = 0; index < 8; index += 1) {
    numbers.push(
      await client.query("SELECT atec.next_mpi_report_number('2026-07-29') AS report_number")
    )
  }
  assert.deepEqual(
    numbers.map(result => result.rows[0].report_number),
    [
      "MPI-2026-000001",
      "MPI-2026-000002",
      "MPI-2026-000003",
      "MPI-2026-000004",
      "MPI-2026-000005",
      "MPI-2026-000006",
      "MPI-2026-000007",
      "MPI-2026-000008"
    ]
  )

  const users = await client.query(`
    INSERT INTO atec.tblusers (username, fullname, role)
    VALUES ('level1', 'Level One', 'INSPECTOR'), ('level2', 'Level Two', 'INSPECTOR')
    RETURNING userid, username
  `)
  const level1User = users.rows.find(row => row.username === "level1").userid
  const level2User = users.rows.find(row => row.username === "level2").userid
  const qualifications = await client.query(
    `
    INSERT INTO atec.tbluserndtqualification (
      userid, qualification_scheme, qualification_level, certificate_number,
      qualified_on, expires_on
    )
    VALUES
      ($1, 'Written Practice', 1, 'MT-L1-UAT', '2026-01-01', '2027-01-01'),
      ($2, 'Written Practice', 2, 'MT-L2-UAT', '2026-01-01', '2027-01-01')
    RETURNING qualificationid, qualification_level
    `,
    [level1User, level2User]
  )
  const level1Qualification = qualifications.rows.find(row => row.qualification_level === 1).qualificationid
  const level2Qualification = qualifications.rows.find(row => row.qualification_level === 2).qualificationid
  const updatedQualification = await client.query(
    `
    INSERT INTO atec.tbluserndtqualification (
      userid, qualification_scheme, ndt_method, qualification_level,
      certificate_number, qualified_on, expires_on, status
    )
    VALUES ($1, 'Updated Written Practice', 'MT', 2, 'MT-L2-UAT', '2026-01-02', '2027-02-01', 'ACTIVE')
    ON CONFLICT (userid, ndt_method, certificate_number)
      WHERE status = 'ACTIVE'
    DO UPDATE SET
      qualification_scheme=EXCLUDED.qualification_scheme,
      qualification_level=EXCLUDED.qualification_level,
      qualified_on=EXCLUDED.qualified_on,
      expires_on=EXCLUDED.expires_on,
      updated_at=now()
    RETURNING qualificationid, qualification_scheme
    `,
    [level2User]
  )
  assert.equal(updatedQualification.rows[0].qualificationid, level2Qualification)
  assert.equal(updatedQualification.rows[0].qualification_scheme, "Updated Written Practice")

  const customer = await client.query(
    "INSERT INTO atec.tblclients (clientname) VALUES ('MPI UAT Customer') RETURNING clientid"
  )
  const clientId = customer.rows[0].clientid
  const report = await client.query(
    `
    INSERT INTO atec.tblndtreport (
      report_number, subject_type, clientid, client_name_snapshot,
      item_description, serial_number, test_date, procedure_used,
      acceptance_standard, area_tested, surface_condition, examination_scope,
      primary_outcome, indication_summary, performing_user_id,
      created_by_user_id, updated_by_user_id
    )
    VALUES (
      'MPI-2026-000009', 'EXTERNAL', $1, 'MPI UAT Customer',
      'External weld coupon', 'UAT-001', '2026-07-29', 'MPI-PROC-UAT',
      'MPI-ACCEPT-UAT', 'Weld and HAZ', 'Clean and dry', 'Full accessible length',
      'ACCEPTABLE', 'NO_RELEVANT_INDICATIONS', $2, $2, $2
    )
    RETURNING ndtreportid
    `,
    [clientId, level1User]
  )
  const reportId = report.rows[0].ndtreportid

  await client.query(
    `
    INSERT INTO atec.tblndtmpdetail (
      ndtreportid, current_type, particle_medium, viewing_method
    )
    VALUES ($1, 'AC', 'WET_INK', 'VISIBLE_CONTRAST')
    `,
    [reportId]
  )
  await client.query(
    `
    INSERT INTO atec.tblndtindication (
      ndtreportid, sequence_number, confirmed_classification,
      relevance, code_disposition, diagram_number, diagram_x, diagram_y
    )
    VALUES ($1, 1, 'ROUNDED', 'NON_RELEVANT', 'ACCEPTABLE', 1, 0.25, 0.5)
    `,
    [reportId]
  )

  await assert.rejects(
    client.query(
      "UPDATE atec.tblndtreport SET status='CERTIFIED', certified_at=now() WHERE ndtreportid=$1",
      [reportId]
    ),
    /chk_tblndtreport_certification/
  )

  await client.query(
    `
    UPDATE atec.tblndtreport
    SET
      status='AWAITING_LEVEL_2',
      performing_qualification_id=$1,
      performing_snapshot='{"qualification_level":1}'::jsonb,
      level2_certification_required=true,
      technician_signed_at=now()
    WHERE ndtreportid=$2
    `,
    [level1Qualification, reportId]
  )
  await client.query(
    `
    UPDATE atec.tblndtreport
    SET
      status='CERTIFIED',
      certifying_user_id=$1,
      certifying_qualification_id=$2,
      certifying_snapshot='{"qualification_level":2}'::jsonb,
      certified_at=now()
    WHERE ndtreportid=$3
    `,
    [level2User, level2Qualification, reportId]
  )
  await client.query(
    "UPDATE atec.tblndtreport SET status='ISSUED', issued_at=now() WHERE ndtreportid=$1",
    [reportId]
  )

  const revision = await client.query(
    `
    INSERT INTO atec.tblndtreport (
      report_number, report_revision, subject_type, clientid,
      client_name_snapshot, item_description, test_date, procedure_used,
      acceptance_standard, area_tested, surface_condition, performing_user_id,
      supersedes_report_id, created_by_user_id, updated_by_user_id
    )
    SELECT
      report_number, report_revision + 1, subject_type, clientid,
      client_name_snapshot, item_description, test_date, procedure_used,
      acceptance_standard, area_tested, surface_condition, performing_user_id,
      ndtreportid, $2, $2
    FROM atec.tblndtreport
    WHERE ndtreportid=$1
    RETURNING ndtreportid, report_revision
    `,
    [reportId, level2User]
  )
  assert.equal(revision.rows[0].report_revision, 1)

  await assert.rejects(
    client.query(
      `
      INSERT INTO atec.tblndtreport (
        report_number, report_revision, subject_type, clientid,
        client_name_snapshot, item_description, test_date, procedure_used,
        acceptance_standard, area_tested, surface_condition
      )
      VALUES (
        'MPI-2026-000009', 1, 'EXTERNAL', $1,
        'MPI UAT Customer', 'Duplicate revision', '2026-07-29', 'P',
        'A', 'Weld', 'Clean'
      )
      `,
      [clientId]
    ),
    /uq_tblndtreport_number_revision/
  )

  const delivery = await client.query(
    `
    INSERT INTO atec.tblndtreportdelivery (
      ndtreportid, report_revision, recipient_email, email_subject,
      delivery_status, sent_by_user_id, sent_at
    )
    VALUES ($1, 0, 'customer@example.com', 'MPI customer report', 'SENT', $2, now())
    RETURNING delivery_status
    `,
    [reportId, level2User]
  )
  assert.equal(delivery.rows[0].delivery_status, "SENT")

  const stored = await client.query(
    `
    SELECT report_number, report_revision, status, level2_certification_required
    FROM atec.tblndtreport
    WHERE ndtreportid=$1
    `,
    [reportId]
  )
  assert.deepEqual(stored.rows[0], {
    report_number: "MPI-2026-000009",
    report_revision: 0,
    status: "ISSUED",
    level2_certification_required: true
  })
}

async function main() {
  const uat = new Client(connectionConfig(process.env.DB_NAME || "postgres"))
  let originalQuery
  try {
    await uat.connect()
    originalQuery = uat.query.bind(uat)
    uat.query = (config, values, callback) => {
      if (typeof config === "string") {
        return originalQuery(config.replace(/\batec\./g, `${schemaName}.`), values, callback)
      }
      if (config && typeof config === "object" && typeof config.text === "string") {
        return originalQuery(
          { ...config, text: config.text.replace(/\batec\./g, `${schemaName}.`) },
          values,
          callback
        )
      }
      return originalQuery(config, values, callback)
    }
    await bootstrap(uat)
    await runAssertions(uat)
    console.log(`MPI database-backed UAT checks passed in isolated schema ${schemaName}.`)
  } finally {
    if (originalQuery) {
      await originalQuery(`DROP SCHEMA IF EXISTS "${schemaName}" CASCADE`).catch(() => {})
    }
    await uat.end().catch(() => {})
  }
}

main().catch(error => {
  console.error(error)
  process.exitCode = 1
})
